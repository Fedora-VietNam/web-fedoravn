import { cn } from "@/lib/utils"

/**
 * @brief Component for displaying keyboard shortcuts or key combinations.
 *
 * @param props.className - Additional CSS classes for the kbd element
 * @returns A JSX element representing a keyboard key
 */
function Kbd({ className, ...props }: React.ComponentProps<"kbd">) {
  return (
    <kbd
      data-slot="kbd"
      className={cn(
        "pointer-events-none inline-flex h-5 w-fit min-w-5 items-center justify-center gap-1 rounded-sm bg-muted px-1 font-sans text-xs font-medium text-muted-foreground select-none in-data-[slot=tooltip-content]:bg-background/20 in-data-[slot=tooltip-content]:text-background dark:in-data-[slot=tooltip-content]:bg-background/10 [&_svg:not([class*='size-'])]:size-3",
        className
      )}
      {...props}
    />
  )
}

/**
 * @brief Container component for grouping multiple Kbd components together.
 *
 * @param props.className - Additional CSS classes for the container
 * @returns A JSX element representing a group of keyboard keys
 */
function KbdGroup({ className, ...props }: React.ComponentProps<"div">) {
  return (
    <kbd
      data-slot="kbd-group"
      className={cn("inline-flex items-center gap-1", className)}
      {...props}
    />
  )
}

export { Kbd, KbdGroup }
